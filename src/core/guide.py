import re

# 目標の具体性：数字・回数・場面・条件を示す手がかり
CONCRETE_HINTS = ("回", "分", "％", "%", "割", "枚", "人", "場面", "とき", "時間",
                  "までに", "までに", "自分から", "自分で", "見て", "聞いて")

NEGATIVE_FOCUS = ("できない", "苦手", "ダメ", "問題", "困った子", "落ち着きがない")


def check_goal_quality(text: str) -> list:
    """目標文の質（ハンドブックp11準拠）を検査する。"""
    issues = []
    t = text or ""
    if not t.strip():
        return issues
    if not any(h in t for h in CONCRETE_HINTS):
        issues.append({"level": "info", "rule": "目標の具体性",
                       "msg": "目標に基準や条件（回数・時間・場面・「自分から」等）を入れると、達成の評価がしやすくなります（ハンドブックp11）。"})
    neg = [w for w in NEGATIVE_FOCUS if w in t]
    if neg:
        issues.append({"level": "warn", "rule": "肯定的表現", "hit": neg[0],
                       "msg": f"目標は「{neg[0]}」などの否定的表現より、目指す姿を肯定的に書くと、子どもが見通しをもてます。具体的な行動で書き換えてください。"})
    return issues


